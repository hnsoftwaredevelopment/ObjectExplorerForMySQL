using System;
using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.Linq;
using System.Text;
using System.Text.RegularExpressions;
using System.Threading;
using System.Threading.Tasks;
using ObjectExplorerForMySql.Core.Connections;
using ObjectExplorerForMySql.Core.DragDrop;
using ObjectExplorerForMySql.Core.Metadata;

namespace ObjectExplorerForMySql.Core.Scripting;

/// <summary>Part of the database script that is being written (US-0603).</summary>
public enum DatabaseScriptStep
{
    /// <summary>CREATE TABLE statements.</summary>
    Tables,

    /// <summary>INSERT statements with the rows of a table.</summary>
    Data,

    /// <summary>CREATE FUNCTION statements.</summary>
    Functions,

    /// <summary>CREATE PROCEDURE statements.</summary>
    Procedures,

    /// <summary>CREATE VIEW statements.</summary>
    Views,

    /// <summary>CREATE TRIGGER statements.</summary>
    Triggers,

    /// <summary>CREATE EVENT statements.</summary>
    Events,
}

/// <summary>Progress of Script Database: the step, the object and its position in the step.</summary>
public sealed record DatabaseScriptProgress(DatabaseScriptStep Step, string Name, int Current, int Total);

/// <summary>Options of Script Database (US-0603). Data is all or nothing (decision D-7).</summary>
public sealed record DatabaseScriptOptions
{
    /// <summary>Gets a value indicating whether the script starts with CREATE DATABASE and USE.</summary>
    public bool IncludeCreateDatabase { get; init; } = true;

    /// <summary>Gets a value indicating whether the script contains INSERT statements with all rows of every table.</summary>
    public bool IncludeData { get; init; }

    /// <summary>Gets the quoting options; the script uses the setting for .sql files.</summary>
    public DropFormatOptions Quoting { get; init; } = DropFormatOptions.Default;

    /// <summary>Gets the connection name for the header comment.</summary>
    public string? ConnectionLabel { get; init; }

    /// <summary>Gets the time for the header comment; null leaves the time out.</summary>
    public DateTime? GeneratedAt { get; init; }
}

/// <summary>What Script Database wrote.</summary>
public sealed class DatabaseScriptResult
{
    /// <summary>Gets the number of objects (tables, views, routines, triggers, events) in the script.</summary>
    public int ObjectCount { get; internal set; }

    /// <summary>Gets the number of rows in INSERT statements.</summary>
    public long RowCount { get; internal set; }

    /// <summary>Gets the objects the server returned no source for (for example routines of another definer).</summary>
    public IList<string> MissingSource { get; } = new List<string>();
}

/// <summary>
/// Writes a script that recreates a database (US-0603): CREATE DATABASE and USE, tables in foreign key order, the data,
/// functions, procedures, views in dependency order, triggers and events. Triggers follow the data, so they do not
/// fire while the rows load.
/// </summary>
public sealed class DatabaseScripter
{
    /// <summary>Maximum number of rows per INSERT statement.</summary>
    public const int RowsPerInsert = 100;

    /// <summary>An INSERT statement is closed once its values pass this length, to stay below max_allowed_packet.</summary>
    public const int MaxInsertLength = 1_000_000;

    private static readonly Regex OrReplacePattern = new(@"^(?<create>\s*CREATE)\s+(?!OR\s+REPLACE\b)", RegexOptions.IgnoreCase | RegexOptions.CultureInvariant);

    private readonly IMetadataProvider _metadata;

    /// <summary>Initializes a new instance of the <see cref="DatabaseScripter"/> class.</summary>
    public DatabaseScripter(IMetadataProvider metadata)
    {
        _metadata = metadata ?? throw new ArgumentNullException(nameof(metadata));
    }

    /// <summary>Writes the script of <paramref name="database"/> to <paramref name="writer"/>.</summary>
    public async Task<DatabaseScriptResult> WriteAsync(
        ConnectionDefinition definition,
        string database,
        TextWriter writer,
        DatabaseScriptOptions options,
        IProgress<DatabaseScriptProgress>? progress,
        CancellationToken cancellationToken)
    {
        if (definition is null)
        {
            throw new ArgumentNullException(nameof(definition));
        }

        if (writer is null)
        {
            throw new ArgumentNullException(nameof(writer));
        }

        options ??= new DatabaseScriptOptions();
        var result = new DatabaseScriptResult();
        var o = options.Quoting;

        writer.WriteLine($"-- Database {database}{(string.IsNullOrEmpty(options.ConnectionLabel) ? string.Empty : " on " + options.ConnectionLabel)}");
        if (options.GeneratedAt is { } generatedAt)
        {
            writer.WriteLine("-- Generated by Object Explorer for MySQL on " + generatedAt.ToString("yyyy-MM-dd HH:mm", CultureInfo.InvariantCulture));
        }

        writer.WriteLine();

        if (options.IncludeCreateDatabase)
        {
            cancellationToken.ThrowIfCancellationRequested();
            var create = await _metadata.GetCreateDatabaseStatementAsync(definition, database, cancellationToken).ConfigureAwait(false)
                ?? "CREATE DATABASE IF NOT EXISTS " + MySqlIdentifier.Quote(database);
            writer.WriteLine(Unquote(create, o).Trim().TrimEnd(';') + ";");
            writer.WriteLine("USE " + o.QuoteForSql(database) + ";");
            writer.WriteLine();
        }

        // As mysqldump: no foreign key checks while tables and rows load, 0 stays 0 in AUTO_INCREMENT columns,
        // TIMESTAMP values in UTC (they are read in UTC). The settings are restored before the code objects, so
        // routines and triggers get the SQL mode of the session that runs the script.
        writer.WriteLine("SET NAMES utf8mb4;");
        writer.WriteLine("SET @OLD_FOREIGN_KEY_CHECKS = @@FOREIGN_KEY_CHECKS, FOREIGN_KEY_CHECKS = 0;");
        writer.WriteLine("SET @OLD_SQL_MODE = @@SQL_MODE, SQL_MODE = 'NO_AUTO_VALUE_ON_ZERO';");
        writer.WriteLine("SET @OLD_TIME_ZONE = @@TIME_ZONE, TIME_ZONE = '+00:00';");
        writer.WriteLine();

        var tables = await _metadata.GetTablesAsync(definition, database, cancellationToken).ConfigureAwait(false);
        var dependencies = await _metadata.GetTableDependenciesAsync(definition, database, cancellationToken).ConfigureAwait(false);
        var tableOrder = DependencyOrder.Sort(tables.Select(t => t.Name), dependencies.Select(d => (d.Table, d.ReferencedTable)));

        await WriteObjectsAsync(definition, writer, options, result, progress, DatabaseScriptStep.Tables, "Tables", tableOrder.Select(n => new CodeObject(CodeObjectKind.Table, database, n)).ToList(), cancellationToken).ConfigureAwait(false);

        if (options.IncludeData)
        {
            writer.WriteLine("-- Data");
            writer.WriteLine();
            for (var i = 0; i < tableOrder.Count; i++)
            {
                cancellationToken.ThrowIfCancellationRequested();
                progress?.Report(new DatabaseScriptProgress(DatabaseScriptStep.Data, tableOrder[i], i + 1, tableOrder.Count));
                await WriteDataAsync(definition, database, tableOrder[i], writer, o, result, cancellationToken).ConfigureAwait(false);
            }
        }

        // Tools such as DBeaver can run this part in another session than the header. The @OLD_ variables are then
        // NULL and MySQL refuses NULL for these settings (error 1231), so the global value is the fallback.
        writer.WriteLine("SET FOREIGN_KEY_CHECKS = IFNULL(@OLD_FOREIGN_KEY_CHECKS, 1);");
        writer.WriteLine("SET SQL_MODE = IFNULL(@OLD_SQL_MODE, @@GLOBAL.SQL_MODE);");
        writer.WriteLine("SET TIME_ZONE = IFNULL(@OLD_TIME_ZONE, @@GLOBAL.TIME_ZONE);");
        writer.WriteLine();

        var functions = await _metadata.GetRoutinesAsync(definition, database, RoutineType.Function, cancellationToken).ConfigureAwait(false);
        await WriteObjectsAsync(definition, writer, options, result, progress, DatabaseScriptStep.Functions, "Functions", functions.Select(r => new CodeObject(CodeObjectKind.Function, database, r.Name)).ToList(), cancellationToken).ConfigureAwait(false);

        var procedures = await _metadata.GetRoutinesAsync(definition, database, RoutineType.Procedure, cancellationToken).ConfigureAwait(false);
        await WriteObjectsAsync(definition, writer, options, result, progress, DatabaseScriptStep.Procedures, "Procedures", procedures.Select(r => new CodeObject(CodeObjectKind.Procedure, database, r.Name)).ToList(), cancellationToken).ConfigureAwait(false);

        // Views come after the functions they may call. A view that uses another view follows it.
        var views = await _metadata.GetViewsAsync(definition, database, cancellationToken).ConfigureAwait(false);
        var viewSources = await FetchAsync(definition, progress, DatabaseScriptStep.Views, views.Select(v => new CodeObject(CodeObjectKind.View, database, v.Name)).ToList(), cancellationToken).ConfigureAwait(false);
        var viewOrder = DependencyOrder.Sort(viewSources.Select(v => v.Code.Name), ViewDependencies(database, viewSources));
        // CREATE OR REPLACE, so running the script again on an existing database does not stop at error 1050.
        var byName = viewSources.ToDictionary(v => v.Code.Name, v => (v.Code, Source: OrReplace(v.Source)), StringComparer.OrdinalIgnoreCase);
        WriteSection(writer, options, result, "Views", viewOrder.Select(n => byName[n]).ToList());

        var triggers = new List<CodeObject>();
        foreach (var table in tableOrder)
        {
            cancellationToken.ThrowIfCancellationRequested();
            var tableTriggers = await _metadata.GetTriggersAsync(definition, database, table, cancellationToken).ConfigureAwait(false);
            triggers.AddRange(tableTriggers.Select(t => new CodeObject(CodeObjectKind.Trigger, database, t.Name)));
        }

        await WriteObjectsAsync(definition, writer, options, result, progress, DatabaseScriptStep.Triggers, "Triggers", triggers, cancellationToken).ConfigureAwait(false);

        var events = await _metadata.GetEventsAsync(definition, database, cancellationToken).ConfigureAwait(false);
        await WriteObjectsAsync(definition, writer, options, result, progress, DatabaseScriptStep.Events, "Events", events.Select(e => new CodeObject(CodeObjectKind.Event, database, e.Name)).ToList(), cancellationToken).ConfigureAwait(false);

        await writer.FlushAsync().ConfigureAwait(false);
        return result;
    }

    /// <summary>
    /// Returns the views each view uses. SHOW CREATE VIEW names every table and view with its database:
    /// <c>`sakila`.`actor`</c>. This works on MySQL and MariaDB alike (MariaDB has no VIEW_TABLE_USAGE).
    /// </summary>
    internal static IEnumerable<(string Name, string DependsOn)> ViewDependencies(string database, IReadOnlyList<(CodeObject Code, string? Source)> views)
    {
        foreach (var (code, source) in views)
        {
            if (source is null)
            {
                continue;
            }

            foreach (var (other, _) in views)
            {
                var reference = MySqlIdentifier.Quote(database) + "." + MySqlIdentifier.Quote(other.Name);
                if (!ReferenceEquals(code, other) && source.IndexOf(reference, StringComparison.OrdinalIgnoreCase) >= 0)
                {
                    yield return (code.Name, other.Name);
                }
            }
        }
    }

    /// <summary>
    /// Turns <c>CREATE ALGORITHM=... VIEW</c> into <c>CREATE OR REPLACE ALGORITHM=... VIEW</c>. A statement that
    /// already has OR REPLACE, or does not start with CREATE, stays as it is.
    /// </summary>
    internal static string? OrReplace(string? statement) =>
        statement is null ? null : OrReplacePattern.Replace(statement, "${create} OR REPLACE ", 1);

    private static string Unquote(string statement, DropFormatOptions options) =>
        options.SqlQuoting == QuoteMode.Always ? statement : MySqlIdentifier.UnquoteWhereSafe(statement);

    private async Task WriteObjectsAsync(
        ConnectionDefinition definition,
        TextWriter writer,
        DatabaseScriptOptions options,
        DatabaseScriptResult result,
        IProgress<DatabaseScriptProgress>? progress,
        DatabaseScriptStep step,
        string title,
        IReadOnlyList<CodeObject> objects,
        CancellationToken cancellationToken)
    {
        var sources = await FetchAsync(definition, progress, step, objects, cancellationToken).ConfigureAwait(false);
        WriteSection(writer, options, result, title, sources);
    }

    private async Task<IReadOnlyList<(CodeObject Code, string? Source)>> FetchAsync(
        ConnectionDefinition definition,
        IProgress<DatabaseScriptProgress>? progress,
        DatabaseScriptStep step,
        IReadOnlyList<CodeObject> objects,
        CancellationToken cancellationToken)
    {
        var sources = new List<(CodeObject, string?)>(objects.Count);
        for (var i = 0; i < objects.Count; i++)
        {
            cancellationToken.ThrowIfCancellationRequested();
            progress?.Report(new DatabaseScriptProgress(step, objects[i].Name, i + 1, objects.Count));
            var source = await _metadata.GetCreateStatementAsync(definition, objects[i], cancellationToken).ConfigureAwait(false);
            sources.Add((objects[i], source));
        }

        return sources;
    }

    private static void WriteSection(TextWriter writer, DatabaseScriptOptions options, DatabaseScriptResult result, string title, IReadOnlyList<(CodeObject Code, string? Source)> sources)
    {
        if (sources.Count == 0)
        {
            return;
        }

        writer.WriteLine("-- " + title);
        writer.WriteLine();
        foreach (var (code, source) in sources)
        {
            if (source is null)
            {
                writer.WriteLine($"-- {code.Kind} {code.Name}: the server returned no source (the account may lack the privilege to see it).");
                writer.WriteLine();
                result.MissingSource.Add($"{code.Kind} {code.Name}");
                continue;
            }

            writer.Write(CodeDocument.Body(code, Unquote(source, options.Quoting)));
            writer.WriteLine();
            result.ObjectCount++;
        }
    }

    private async Task WriteDataAsync(ConnectionDefinition definition, string database, string table, TextWriter writer, DropFormatOptions o, DatabaseScriptResult result, CancellationToken cancellationToken)
    {
        // Generated columns get their value from the expression; MySQL refuses a value for them.
        var columns = (await _metadata.GetColumnsAsync(definition, database, table, cancellationToken).ConfigureAwait(false))
            .Where(c => !c.IsGenerated)
            .ToList();
        if (columns.Count == 0)
        {
            return;
        }

        var prefix = $"INSERT INTO {o.QuoteForSql(table)} ({string.Join(", ", columns.Select(c => o.QuoteForSql(c.Name)))}) VALUES";
        var batch = new List<string>(RowsPerInsert);
        var length = 0;
        var nl = writer.NewLine;
        var rowsBefore = result.RowCount;

        void Flush()
        {
            if (batch.Count == 0)
            {
                return;
            }

            writer.WriteLine(prefix);
            writer.Write(string.Join("," + nl, batch));
            writer.WriteLine(";");
            batch.Clear();
            length = 0;
        }

        await _metadata.ReadRowsAsync(
            definition,
            database,
            table,
            columns.Select(c => c.Name).ToList(),
            values =>
            {
                cancellationToken.ThrowIfCancellationRequested();
                var builder = new StringBuilder("(");
                for (var i = 0; i < values.Length; i++)
                {
                    if (i > 0)
                    {
                        builder.Append(", ");
                    }

                    builder.Append(SqlLiteral.Format(values[i], columns[i].DataType));
                }

                var row = builder.Append(')').ToString();
                batch.Add(row);
                length += row.Length;
                result.RowCount++;
                if (batch.Count >= RowsPerInsert || length >= MaxInsertLength)
                {
                    Flush();
                }
            },
            cancellationToken).ConfigureAwait(false);

        var hadRows = result.RowCount > rowsBefore;
        Flush();
        if (hadRows)
        {
            writer.WriteLine();
        }
    }
}
